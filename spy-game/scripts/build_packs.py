def lines(block):
    return [l.strip() for l in block.strip().splitlines() if l.strip()]


def main():
    packs = []
    for pid, (name, icon, block) in PLACES.items():
        items = []
        for line in lines(block):
            iid, n, roles = [p.strip() for p in line.split("|")]
            items.append({"id": iid, "name_ar": n, "roles_ar": [r.strip() for r in roles.split("،") if r.strip()]})
        packs.append({"id": pid, "name_ar": name, "icon": icon, "mode": "places", "items": items})
    for pid, (name, icon, block) in WORDS.items():
        items = []
        for line in lines(block):
            parts = [p.strip() for p in line.split("|")]
            item = {"id": parts[0], "name_ar": parts[1]}
            if len(parts) > 2 and parts[2]:
                item["close_ar"] = parts[2]
            items.append(item)
        packs.append({"id": pid, "name_ar": name, "icon": icon, "mode": "words", "items": items})
    out = {"version": 1, "packs": packs, "dares": lines(DARES)}
    path = pathlib.Path(__file__).resolve().parent.parent / "app" / "content" / "packs.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {path} — {len(packs)} packs, {sum(len(p['items']) for p in packs)} items")


if __name__ == "__main__":
    main()
